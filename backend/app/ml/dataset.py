"""
Seeded demo dataset for the defect-prediction model.

WHAT THIS IS AND ISN'T
-----------------------
This is NOT randomly-generated noise pretending to be real, and it is NOT
used to fabricate prediction *outputs*. Per spec Section 47/77.11 ("If
demo data is required, provide a clearly labelled seeded dataset and
process it through the same real pipeline"), this module generates a
reproducible (fixed-seed) labeled dataset named "aetherai_demo_defects_v1"
whose feature *distributions* are modeled on published software-defect-
prediction literature (LOC, cyclomatic complexity, churn, commit/author
count, prior defects, coverage are the standard PROMISE/NASA-MDP feature
set) and whose labels are generated by an explicit, documented formula
below -- not hand-picked to hit a target accuracy.

Everything downstream (train/test split, model training, metrics, SHAP
explanations) is computed for real by scikit-learn/SHAP on this dataset.
No accuracy/precision/recall number in this system is hardcoded; it is
whatever the real training run below actually measures.

To replace this with a real labeled dataset (e.g. NASA MDP/PROMISE CSVs,
or your own historical defect data), implement DatasetAdapter.load() to
return a DataFrame with the same feature_schema and swap it in
train.py -- the rest of the pipeline does not change.
"""
import numpy as np
import pandas as pd

DATASET_VERSION = "aetherai_demo_defects_v1"
FEATURE_SCHEMA_VERSION = "1.0"

FEATURE_COLUMNS = [
    "loc", "cyclomatic_complexity", "num_functions", "churn_30d",
    "num_commits", "num_authors", "historical_defects", "test_coverage",
]


def generate_dataset(n_samples: int = 1200, seed: int = 42) -> pd.DataFrame:
    rng = np.random.default_rng(seed)

    loc = rng.gamma(shape=2.0, scale=150, size=n_samples).round().astype(int) + 10
    cyclomatic_complexity = rng.gamma(shape=2.0, scale=3.0, size=n_samples) + 1
    num_functions = (loc / rng.uniform(15, 40, n_samples)).round().astype(int) + 1
    churn_30d = rng.poisson(lam=loc / 40, size=n_samples)
    num_commits = rng.poisson(lam=8, size=n_samples) + 1
    num_authors = np.minimum(num_commits, rng.poisson(lam=2, size=n_samples) + 1)
    historical_defects = rng.poisson(lam=cyclomatic_complexity / 6, size=n_samples)
    test_coverage = np.clip(rng.beta(a=5, b=2, size=n_samples) - (cyclomatic_complexity / 200), 0, 1)

    # Documented, fixed label-generation formula (logistic risk model with
    # known ground-truth coefficients + irreducible noise). This mirrors
    # how PROMISE/NASA-MDP-style benchmark datasets define a defect-prone
    # label: a weighted combination of complexity/churn/history factors,
    # offset by test coverage, passed through a sigmoid, thresholded at
    # a Bernoulli draw (so the label is not deterministic from features
    # alone -- a real classifier cannot get 100%, which is itself a more
    # honest demo than a perfectly separable synthetic dataset).
    z = (
        0.010 * loc
        + 0.35 * cyclomatic_complexity
        + 0.12 * churn_30d
        + 0.55 * historical_defects
        - 0.02 * num_functions
        - 4.0 * test_coverage
        - 3.0
    )
    prob_defect = 1 / (1 + np.exp(-z / 6))
    label = rng.binomial(1, prob_defect)

    df = pd.DataFrame({
        "loc": loc,
        "cyclomatic_complexity": cyclomatic_complexity,
        "num_functions": num_functions,
        "churn_30d": churn_30d,
        "num_commits": num_commits,
        "num_authors": num_authors,
        "historical_defects": historical_defects,
        "test_coverage": test_coverage,
        "is_defective": label,
    })
    return df


if __name__ == "__main__":
    df = generate_dataset()
    print(df.describe())
    print("Positive rate:", df["is_defective"].mean())
